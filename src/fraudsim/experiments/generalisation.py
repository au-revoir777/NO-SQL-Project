"""
E6b: leave-one-scenario-out scorer and ring-level scorer metrics
(docs/research/e6b_protocol.md). Analysis only: refits on the saved rows of the
shipped scorer's training run; no simulation.

    python -m fraudsim.experiments.generalisation run
    python -m fraudsim.experiments.generalisation report
"""

# ruff: noqa: RUF001  (tables use typographic dashes and signs)

from __future__ import annotations

import argparse
import json
import shutil
from pathlib import Path

import numpy as np
import pandas as pd
from sklearn.metrics import average_precision_score, roc_auc_score

from fraudsim.experiments.harness import ROOT, _append
from fraudsim.experiments.provenance import recorded
from fraudsim.logging.replay import file_sha256
from fraudsim.scoring.features import FEATURE_NAMES
from fraudsim.scoring.scorer import RingScorer

TRAINING_ID = "dd98f740ea8c"
SRC = ROOT / "runs/training" / TRAINING_ID
OUT = ROOT / "results/e6b_generalisation"
FIT_FRACTION = 0.7
SHIPPED = ROOT / "models/ring_scorer_lr.json"


def _xy(df: pd.DataFrame) -> tuple[np.ndarray, np.ndarray]:
    return df[list(FEATURE_NAMES)].to_numpy(dtype=float), df["label"].to_numpy(dtype=int)


def fit(train: pd.DataFrame) -> RingScorer:
    fit_rows = train[train["t_frac"] < FIT_FRACTION]
    cal_rows = train[train["t_frac"] >= FIT_FRACTION]
    return RingScorer("logistic_regression").fit(*_xy(fit_rows), *_xy(cal_rows))


def ring_units(test: pd.DataFrame, scores: np.ndarray) -> pd.DataFrame:
    t = test[["scenario", "seed", "ring_id", "label"]].copy()
    t["score"] = scores
    return t.groupby(["scenario", "seed", "ring_id"]).agg(
        score=("score", "max"), label=("label", "max")
    )


def metrics(scorer: RingScorer, test: pd.DataFrame) -> dict[str, float | int | None]:
    x, y = _xy(test)
    snap = scorer.evaluate(x, y)
    units = ring_units(test, scorer.predict(x))
    both = units["label"].nunique() == 2
    return {
        "snap_n": len(test),
        "snap_pos": int(y.sum()),
        "snap_roc_auc": snap["roc_auc"],
        "snap_pr_auc": snap["pr_auc"],
        "snap_ece": snap["ece"],
        "snap_brier": snap["brier"],
        "ring_n": len(units),
        "ring_pos": int(units["label"].sum()),
        "ring_roc_auc": round(float(roc_auc_score(units["label"], units["score"])), 6)
        if both
        else None,
        "ring_pr_auc": round(float(average_precision_score(units["label"], units["score"])), 6)
        if both
        else None,
    }


def run() -> Path:
    rows_dir = OUT / "rows"
    rows_dir.mkdir(parents=True, exist_ok=True)
    for name in ("train_rows.csv", "test_rows.csv"):
        shutil.copyfile(SRC / name, rows_dir / name)
    train = pd.read_csv(rows_dir / "train_rows.csv")
    test = pd.read_csv(rows_dir / "test_rows.csv")
    details = {
        "protocol": "docs/research/e6b_protocol.md",
        "training_id": TRAINING_ID,
        "rows_sha256": {n: file_sha256(rows_dir / n) for n in ("train_rows.csv", "test_rows.csv")},
        "fit_fraction": FIT_FRACTION,
    }
    path = OUT / "results.csv"
    if path.exists():
        path.unlink()
    with recorded(OUT, "e6b_generalisation", details) as entry:
        full = fit(train)
        shipped = json.loads(SHIPPED.read_text(encoding="utf-8"))["metrics"]["test"]
        check = metrics(full, test)
        ok = all(
            abs(float(check[f"snap_{k}"]) - float(shipped[k])) < 0.0015
            for k in ("roc_auc", "pr_auc", "ece", "brier")
        )
        entry["sanity_check"] = {"refit": check, "shipped_test": shipped, "reproduces": ok}
        if not ok:
            raise RuntimeError(f"refit does not reproduce the shipped scorer: {check} vs {shipped}")
        _append(path, {"fold": "all", "held_out": "", "model": "all_scenarios"} | check)
        for s in sorted(test["scenario"].unique()):
            held = test[test["scenario"] == s]
            loso = fit(train[train["scenario"] != s])
            _append(
                path, {"fold": s, "held_out": s, "model": "all_scenarios"} | metrics(full, held)
            )
            _append(
                path, {"fold": s, "held_out": s, "model": "leave_one_out"} | metrics(loso, held)
            )
            print(f"[e6b] {s}: done")
    return path


def report(out_md: Path = ROOT / "docs/research/e6b_tables.md") -> None:
    df = pd.read_csv(OUT / "results.csv")
    allrow = df[df["fold"] == "all"].iloc[0]
    lines = [
        "# E6b tables (generated)",
        "",
        "Generated by `python -m fraudsim.experiments.generalisation report` from",
        f"`results/e6b_generalisation/results.csv` (rows of training run `{TRAINING_ID}`).",
        "",
        "## Shipped procedure, all scenarios: snapshot vs ring level (test seeds 201-205)",
        "",
        "| Level | Units | Positives | ROC AUC | PR AUC |",
        "|---|---|---|---|---|",
        f"| Snapshot | {allrow['snap_n']} | {allrow['snap_pos']} | {allrow['snap_roc_auc']:.3f}"
        f" | {allrow['snap_pr_auc']:.3f} |",
        f"| Ring | {allrow['ring_n']} | {allrow['ring_pos']} | {allrow['ring_roc_auc']:.3f}"
        f" | {allrow['ring_pr_auc']:.3f} |",
        "",
        "## Leave one scenario out (evaluated on the held-out scenario's test rows)",
        "",
        "| Held-out scenario | Model | Snapshot ROC AUC | Snapshot PR AUC | ECE | Brier"
        " | Ring units (pos) | Ring ROC AUC | Ring PR AUC |",
        "|---|---|---|---|---|---|---|---|---|",
    ]

    def f(v: object) -> str:
        return "–" if v is None or (isinstance(v, float) and np.isnan(v)) else f"{float(v):.3f}"

    for _, r in df[df["fold"] != "all"].iterrows():
        lines.append(
            f"| {r['held_out']} | {r['model']} | {f(r['snap_roc_auc'])} | {f(r['snap_pr_auc'])}"
            f" | {f(r['snap_ece'])} | {f(r['snap_brier'])} | {r['ring_n']} ({r['ring_pos']})"
            f" | {f(r['ring_roc_auc'])} | {f(r['ring_pr_auc'])} |"
        )
    out_md.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {out_md}")


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("step", choices=["run", "report"])
    {"run": run, "report": report}[ap.parse_args().step]()


if __name__ == "__main__":
    main()
