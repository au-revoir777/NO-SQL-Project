"""
E5b: the first-hop fan-out limit at large hubs (docs/research/e5b_protocol.md).

    python -m fraudsim.experiments.large_hubs run      # hub sizes 500, 2,000, 10,000
    python -m fraudsim.experiments.large_hubs report   # docs/research/e5b_tables.md
"""

# ruff: noqa: RUF001  (tables use typographic dashes and signs)

from __future__ import annotations

import argparse
import time
from collections.abc import Callable
from pathlib import Path

import pandas as pd

from fraudsim.experiments.harness import PROPOSED, ROOT, Method, _merge, baseline_methods, run_grid
from fraudsim.experiments.learned_baselines import paired
from fraudsim.experiments.tuning import load_tuned
from fraudsim.experiments.weight_functions import _hub_hiding_recall

HUB_SIZES = (500, 2000, 10000)
SEEDS = (1001, 1002, 1003, 1004, 1005)
FULL_BUDGET_S = 2 * 3600  # contingency for the full arms at the largest hub
EXPERIMENT = "e5b_large_hubs"


def _alert() -> float:
    tuned = load_tuned()
    assert tuned is not None, "configs/tuned.json missing"
    return float(tuned["alert_threshold"])


def _m(name: str, label: str, weight: str, edge: float, engine: dict) -> Method:
    return Method(
        name,
        label,
        _merge(PROPOSED, {"hub_aware": {"weight_method": weight, "edge_threshold": edge}}),
        engine=engine,
        family="e5b",
        alert_threshold=_alert(),
    )


def methods() -> dict[str, list[Method]]:
    inc = [
        _m("log_fanout", "1/ln(1+d), fan-out 250/20", "inverse_log_degree", 0.3, {}),
        _m(
            "log_bound",
            "1/ln(1+d), bound crossing",
            "inverse_log_degree",
            0.3,
            {"hub_crossing": "bound"},
        ),
        _m("const_fanout", "constant, fan-out 250/20", "none", 1.0, {}),
        *[m for m in baseline_methods() if m.name in ("static_cap10", "static_cap100")],
    ]
    full = [
        _m(
            "log_full",
            "1/ln(1+d), full recomputation",
            "inverse_log_degree",
            0.3,
            {"incremental": False},
        ),
        _m("const_full", "constant, full recomputation", "none", 1.0, {"incremental": False}),
    ]
    return {"incremental": inc, "full": full}


def overrides(size: int) -> dict[str, int]:
    return {
        "simulation.hub_distribution.mega_office_gateway.size": size,
        "simulation.num_users": max(100, size + 50),
    }


def run(out: Path = ROOT / "results", log: Callable[[str], None] = print) -> Path:
    ms = methods()
    path = Path(out) / EXPERIMENT / "results.csv"
    for size in HUB_SIZES:
        kw = {
            "scenario_overrides": overrides(size),
            "log": log,
            "extra_columns": {"hub_size": size},
        }
        run_grid(EXPERIMENT, ["hub_heavy"], SEEDS, ms["incremental"], Path(out), **kw)
        if size != max(HUB_SIZES):
            run_grid(EXPERIMENT, ["hub_heavy"], SEEDS, ms["full"], Path(out), **kw)
            continue
        # Contingency (protocol): seeds 1001-1003 first; the rest only if the projected
        # total for the full arms stays within the budget.
        t0 = time.perf_counter()
        run_grid(EXPERIMENT, ["hub_heavy"], SEEDS[:3], ms["full"], Path(out), **kw)
        spent = time.perf_counter() - t0
        if spent * len(SEEDS) / 3 <= FULL_BUDGET_S:
            run_grid(EXPERIMENT, ["hub_heavy"], SEEDS[3:], ms["full"], Path(out), **kw)
        else:
            log(f"[e5b] full arms at {size}: {spent:.0f}s for 3 seeds; seeds 1004-1005 skipped")
    return path


def report(out_md: Path = ROOT / "docs/research/e5b_tables.md") -> None:
    df = pd.read_csv(ROOT / "results" / EXPERIMENT / "results.csv")
    df["f1"] = df["f1"].fillna(0)
    order = [
        "log_fanout",
        "log_bound",
        "log_full",
        "const_fanout",
        "const_full",
        "static_cap10",
        "static_cap100",
    ]
    lines = [
        "# E5b tables (generated)",
        "",
        "Generated by `python -m fraudsim.experiments.large_hubs report` from",
        f"`results/{EXPERIMENT}/results.csv`. hub_heavy with the office gateway resized;",
        "means over seeds (n = seeds run). Region: users evaluated per batch (median of",
        "per-run medians; maximum over runs). Latency: mean of per-run median detection ms.",
        "",
        "| Hub size | Method | n | P | R | F1 | Hub-hiding recall | Region p50 | Region max"
        " | Detect ms p50 | Wall s |",
        "|---|---|---|---|---|---|---|---|---|---|---|",
    ]
    for size in HUB_SIZES:
        for m in order:
            g = df[(df["hub_size"] == size) & (df["method"] == m)]
            if g.empty:
                continue
            hh = _hub_hiding_recall(g)
            cells = [
                f"{size:,}",
                m,
                str(len(g)),
                f"{g['precision'].mean():.2f}",
                f"{g['recall'].mean():.2f}",
                f"{g['f1'].mean():.2f}",
                f"{hh:.2f}" if hh is not None else "–",
                f"{g['region_p50'].median():.0f}",
                f"{g['region_max'].max():.0f}",
                f"{g['detect_ms_p50'].mean():.1f}",
                f"{g['wall_s'].mean():.1f}",
            ]
            lines.append("| " + " | ".join(cells) + " |")
    lines += ["", "## Incremental vs full recomputation (same streams)", ""]
    lines += [
        "| Pair | Hub size | Runs | Identical P/R/F1 | Paired Wilcoxon on F1 |",
        "|---|---|---|---|---|",
    ]
    for a, b in (
        ("log_fanout", "log_full"),
        ("log_bound", "log_full"),
        ("const_fanout", "const_full"),
    ):
        for size in HUB_SIZES:
            x = df[(df["hub_size"] == size) & (df["method"] == a)].set_index("seed")
            y = df[(df["hub_size"] == size) & (df["method"] == b)].set_index("seed")
            common = sorted(set(x.index) & set(y.index))
            if not common:
                continue
            same = sum(
                all(
                    abs(float(x.loc[s, c] or 0) - float(y.loc[s, c] or 0)) < 1e-9
                    for c in ("precision", "recall", "f1")
                )
                for s in common
            )
            test = paired(x.loc[common, "f1"].to_list(), y.loc[common, "f1"].to_list())
            lines.append(
                f"| {a} vs {b} | {size:,} | {len(common)} | {same}/{len(common)} | {test} |"
            )
    out_md.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {out_md}")


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("step", choices=["run", "report"])
    {"run": run, "report": report}[ap.parse_args().step]()


if __name__ == "__main__":
    main()
