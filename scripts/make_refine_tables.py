def mac(name: str, value) -> None:
    macros.append(f"\\newcommand{{\\{name}}}{{{value}}}")


def f2(x: float) -> str:
    return f"{x:.2f}"


def f3(x: float) -> str:
    return f"{x:.3f}"


def sgn(x: float, d: int = 2) -> str:
    return ("+" if x > 0 else "$-$" if x < 0 else "") + f"{abs(x):.{d}f}"


def hh(df: pd.DataFrame, m: str, key: str = "hub_hiding") -> str:
    x = n = 0
    for s in df[df.method == m]["detected_by_evasion"].dropna():
        d = json.loads(s)
        if key in d:
            x += d[key][0]
            n += d[key][1]
    return f"{x}/{n}"


