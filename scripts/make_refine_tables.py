def s1() -> None:
    """S1 statistics on the original results (no new runs)."""
    e1 = c.load("results/e1_baselines/results.csv")
    e1b = c.load("results/e1b_scored_baselines/results.csv")
    both = pd.concat([e1, e1b], ignore_index=True)
    k = c.contrast(both, "proposed", "static_cap10_scored")
    hv = k["per_scenario"]["hub_heavy"]
    mac("RfOldHubD", sgn(hv["d"]))
    mac("RfOldHubLo", sgn(hv["ci95"][0]))
    mac("RfOldHubHi", sgn(hv["ci95"][1]))
    mac("RfOldHubWTL", "/".join(map(str, hv["wtl"])))
    mac("RfOldNoiseD", sgn(k["per_scenario"]["high_noise"]["d"]))
    e2 = c.load("results/e2_ablations/results.csv")
    k = c.contrast(e2, "proposed", "no_hub_weight")
    mac("RfAblHubWHub", sgn(k["per_scenario"]["hub_heavy"]["d"]))
    mac("RfAblHubWNoise", sgn(k["per_scenario"]["high_noise"]["d"]))
    from scipy import stats as st
    j = c.pair(e2, "proposed", "no_hub_weight")
    mac("RfAblHubWHet", f"{st.f_oneway(*[g.d.to_numpy() for _, g in j.groupby('scenario')]).pvalue:.3f}")
    for v, key in (("no_hysteresis", "Hyst"), ("no_time_decay", "Decay")):
        k = c.contrast(e2, "proposed", v)
        mac(f"RfAbl{key}Lo", sgn(k["ci90_t"][0], 3))
        mac(f"RfAbl{key}Hi", sgn(k["ci90_t"][1], 3))
    e2c = c.load("results/e2c_weight_functions/results.csv")
    for v, key in (("w_inverse_sqrt_degree", "Sqrt"), ("w_none", "Const")):
        k = c.contrast(e2c, "w_inverse_log_degree", v)
        mac(f"RfW{key}Lo", sgn(k["ci90_t"][0], 3))
        mac(f"RfW{key}Hi", sgn(k["ci90_t"][1], 3))
    fr = json.loads((ROOT / "results/e3b_frontier_ci/frontier_ci.json").read_text())["points"]
    for m, key in (("hubS_0.2", "HubS"), ("capS_0.2", "CapS")):
        mac(f"RfFr{key}RLo", f2(fr[m]["recall_ci"][0]))
        mac(f"RfFr{key}RHi", f2(fr[m]["recall_ci"][1]))
    from s1_stats import newcombe

    e7 = pd.read_csv(ROOT / "results/e7_adaptivity/results.csv")
    on, off = e7[e7.feedback.astype(str).str.lower().isin(["true", "1"])], e7[~e7.feedback.astype(str).str.lower().isin(["true", "1"])]
    lo, hi = newcombe(int(on.adaptive_detected.sum()), int(on.adaptive_rings.sum()),
                      int(off.adaptive_detected.sum()), int(off.adaptive_rings.sum()))
    mac("RfAdaptLo", sgn(lo))
    mac("RfAdaptHi", sgn(hi))


