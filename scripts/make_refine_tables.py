    order = ["proposed", "proposed_const", "w2_gnn_unscored", "w2_gnn", "w2_rules_per_scenario", "w2_rules",
             "w2_louvain", "w2_leiden", "w2_peeling", "tabular_gb"]
    rows = []
    for m in order:
        g = df[df.method == m]
        pr = g.pr_auc.mean()
        if m == "proposed":
            d = "--"
            ci = p = ""
        else:
            k = c.contrast(df, "proposed", m)
            d = sgn(k["diff"], 3)
            ci = f"[{sgn(k['ci95_cluster_boot'][0], 3)}, {sgn(k['ci95_cluster_boot'][1], 3)}]"
            p = "$<$0.001" if k["p_signflip"] < 0.001 else f"{k['p_signflip']:.3f}"
            key = m.replace("w2_", "").replace("_", "")
            mac(f"RfEx{key}D", sgn(k["diff"], 3))
            mac(f"RfEx{key}DA", f3(abs(k["diff"])))
            mac(f"RfEx{key}Lo", sgn(k["ci95_cluster_boot"][0], 3))
            mac(f"RfEx{key}Hi", sgn(k["ci95_cluster_boot"][1], 3))
            mac(f"RfEx{key}P", p)
            mac(f"RfEx{key}Drift", sgn(k["per_scenario"]["drift"]["d"]))
            mac(f"RfEx{key}Noise", sgn(k["per_scenario"]["high_noise"]["d"]))
            mac(f"RfEx{key}Adv", sgn(k["per_scenario"]["adversarial"]["d"]))
        key = m.replace("w2_", "").replace("_", "")
        mac(f"RfEx{key}F", f3(g.f1.mean()))
        mac(f"RfEx{key}PR", "--" if math.isnan(pr) else f3(pr))
        mac(f"RfEx{key}Adapt", hh(df, m, "adaptive"))
        mac(f"RfEx{key}Decoy", hh(df, m, "decoy_edges"))
        mac(f"RfEx{key}HH", hh(df, m))
        ci95 = 1.96 * g.f1.std(ddof=1) / math.sqrt(len(g))
        rows.append(f"{LABEL[m]} & {g.precision.mean():.2f} & {g.recall.mean():.2f} & {g.f1.mean():.3f} $\\pm$ {ci95:.3f} & "
                    f"{'--' if math.isnan(pr) else f'{pr:.3f}'} & {hh(df, m)} & {hh(df, m, 'decoy_edges')} & "
                    f"{hh(df, m, 'adaptive')} & {d} & {ci} & {p} \\\\")
        if m == "proposed_const":
            rows.append("\\midrule")
